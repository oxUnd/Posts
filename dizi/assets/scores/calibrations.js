/* 严格解析，错误必须报告，不能跳过数字或替换成其他八度。 */
window.ScoreNotation = (() => {
  const scale = [null, 0, 2, 4, 5, 7, 9, 11];
  function parseToken(token) {
    const parts = /^([0-7])([,']?)(_*)(\.?)(?::(\d+(?:\.\d+)?))?(~?)$/.exec(token);
    if (!parts || parts[3].length > 3 || (parts[5] && (parts[3] || parts[4]))) {
      throw new Error(`无法解析音符：${token}`);
    }
    const degree = Number(parts[1]);
    const octave = parts[2] === ',' ? -1 : parts[2] === "'" ? 1 : 0;
    const duration = parts[5] ? Number(parts[5]) : (2 ** -parts[3].length) * (parts[4] ? 1.5 : 1);
    if (!(duration > 0 && duration <= 16) || (degree === 0 && (octave || parts[6]))) {
      throw new Error(`非法时值或休止：${token}`);
    }
    return { degree, octave, duration, rest: degree === 0, tie: !!parts[6], token };
  }

  function parseBar(bar) {
    if (typeof bar !== 'string' || !bar.trim()) throw new Error('空小节');
    return bar.trim().split(/\s+/).map(parseToken);
  }

  function barOrder(score) {
    if (score.order) return [...score.order];
    const order = [];
    for (let i = 0; i < score.bars.length; i += 1) {
      const repeat = (score.repeats || []).find(item => item.from === i);
      if (repeat) {
        for (let pass = 0; pass < repeat.times; pass += 1) {
          for (let bar = repeat.from; bar <= repeat.to; bar += 1) order.push(bar);
        }
        i = repeat.to;
      } else order.push(i);
    }
    return order;
  }

  function compile(score) {
    const parsed = score.bars.map(parseBar);
    const events = [];
    for (const barIndex of barOrder(score)) {
      if (!parsed[barIndex]) throw new Error(`反复引用不存在的小节：${barIndex + 1}`);
      parsed[barIndex].forEach((item, tokenIndex) => {
        const event = { ...item, octave: item.octave + (score.octaveShift || 0), barIndex, tokenIndex };
        const last = events[events.length - 1];
        if (last?.tie) {
          if (event.rest || last.degree !== event.degree || last.octave !== event.octave) {
            throw new Error(`第 ${barIndex + 1} 小节延音线两端音高不同`);
          }
          last.duration += event.duration;
          last.tie = event.tie;
        } else events.push(event);
      });
    }
    if (events[events.length - 1]?.tie) throw new Error('末尾延音线缺少后续音符');
    return events;
  }

  function validate(score) {
    const errors = [];
    if (!score || typeof score !== 'object' || !Array.isArray(score.bars) || !score.bars.length) {
      return ['缺少逐小节曲谱数据'];
    }
    if (![2, 3, 4].includes(score.beatsPerBar)) errors.push('缺少有效小节拍数');
    if (![-1, 0].includes(score.octaveShift || 0)) errors.push('非法八度偏移');
    if (![2, 5].includes(score.system)) errors.push('缺少有效指法');
    if (!(score.tempo >= 40 && score.tempo <= 200)) errors.push('缺少有效练习速度');
    score.bars.forEach((bar, index) => {
      try {
        const notes = parseBar(bar);
        const beats = notes.reduce((sum, item) => sum + item.duration, 0);
        const expected = score.barBeats?.[index] ?? score.beatsPerBar;
        if (Math.abs(beats - expected) > 1e-8) errors.push(`第 ${index + 1} 小节 ${beats} 拍，应为 ${expected}`);
        for (const note of notes.filter(item => !item.rest)) {
          const pitch = scale[note.degree] + 12 * (note.octave + (score.octaveShift || 0));
          const [min, max] = score.system === 2 ? [-10, 16] : [-5, 21];
          if (pitch < min || pitch > max) errors.push(`第 ${index + 1} 小节 ${note.token} 超出作${score.system}指法表音域`);
        }
      } catch (error) { errors.push(`第 ${index + 1} 小节：${error.message}`); }
    });
    for (const repeat of score.repeats || []) {
      if (!Number.isInteger(repeat.from) || !Number.isInteger(repeat.to) || repeat.from < 0 ||
          repeat.to >= score.bars.length || repeat.from > repeat.to || !Number.isInteger(repeat.times) ||
          repeat.times < 2 || repeat.times > 4) errors.push('非法反复范围');
    }
    try { compile(score); } catch (error) { errors.push(error.message); }
    for (const [bar, reason] of Object.entries(score.review || {})) errors.push(`第 ${Number(bar) + 1} 小节待核：${reason}`);
    return errors;
  }
  return { parseToken, parseBar, barOrder, compile, validate };
})();
